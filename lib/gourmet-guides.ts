const sceneStyle = (
  slug: string,
  label: string,
  text: string,
): GourmetGuideStyle[] => {
  const scene = gourmetScenes.find((s) => s.slug === slug)
  return scene ? [{ label, keys: [], text, match: scene.match }] : []
}

